CREATE TABLE COLMEIA (
    NOME_COL VARCHAR2(30),
    NUMERO NUMBER(4, 0),
    ESTADO VARCHAR2(20) NOT NULL,
    ESPECIE VARCHAR2(20) NOT NULL,
    LATITUDE NUMBER(9,6) NOT NULL,
    LONGITUDE NUMBER(9,6) NOT NULL,
    
     -- restrição dos dados de latitude(+- 90) e longitude(+- 180)
    CONSTRAINT CK_COORDENADA_LAT CHECK(LATITUDE > -90.0 AND LATITUDE < 90.0),
    CONSTRAINT CK_COORDENADA_LON CHECK(LONGITUDE > -180.0 AND LONGITUDE < 180.0),
    
    CONSTRAINT PK_COLMEIA PRIMARY KEY(NOME_COL, NUMERO),
    CONSTRAINT FK_NOME_COL FOREIGN KEY (NOME_COL) REFERENCES APIARIO(NOME) ON DELETE CASCADE
    );

-- Trigger que atualiza o numero total de colmeias em cada apiario:
CREATE OR REPLACE TRIGGER TRG_CONTA_COLMEIAS
AFTER INSERT ON COLMEIA
FOR EACH ROW
BEGIN
    UPDATE APIARIO
    SET COLMEIAS = COLMEIAS + 1
    WHERE NOME = :NEW.NOME_COL;
END;
