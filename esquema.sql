CREATE TABLE APIARIO (
    NOME VARCHAR2(30),
    CPF_RESPONSAVEL VARCHAR2(14) NOT NULL,
    AMBIENTE VARCHAR2(20) NOT NULL,
    ESTADO CHAR(2) NOT NULL,
    CIDADE VARCHAR2(20) NOT NULL,
    RUA VARCHAR2(20) NOT NULL,
    NUMERO NUMBER(4,0) NOT NULL,
    COLMEIAS NUMBER(4,0) DEFAULT 0,
    
    CONSTRAINT PK_APIARIO PRIMARY KEY(NOME),
    CONSTRAINT FK_APIARIO FOREIGN KEY (CPF_RESPONSAVEL) REFERENCES FUNCIONARIO(CPF),
    CONSTRAINT UK_APIARIO UNIQUE (CPF_RESPONSAVEL) 
    );
    
-- Trigger para verificar se o responsavel é supervisor:    
CREATE OR REPLACE TRIGGER TRG_RESPONSAVEL_APIARIO
BEFORE INSERT OR UPDATE ON APIARIO
FOR EACH ROW
DECLARE
    T_FUNCAO VARCHAR2(20);
BEGIN
    SELECT FUNCAO
    INTO T_FUNCAO
    FROM FUNCIONARIO
    WHERE CPF = :NEW.CPF_RESPONSAVEL;
    
    IF UPPER(T_FUNCAO) != 'SUPERVISOR' THEN
        RAISE_APPLICATION_ERROR(
            -20003,
            'Funcionario não ocupa a função de supervisor.'
        );
    END IF;
END;
/
    
